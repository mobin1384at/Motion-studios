#!/usr/bin/env python3
"""captions.py — convert SRT (or word-timing JSON) to RTL-safe ASS subtitles.

Rules (research §4-5, persian-rtl):
  * Persian text is NEVER rendered with ffmpeg drawtext (it breaks shaping
    and bidi). Output is ASS for the ffmpeg `subtitles`/`ass` filter
    (libass), which shapes and bidi-orders correctly.
  * Every line containing Persian is wrapped in bidi isolates: RLI (U+2067)
    ... PDI (U+2069). RLI is isolating (unlike RLE) and is honoured by
    VLC/mpv/fribidi.
  * Font family is Vazirmatn (fallback Tahoma if Vazirmatn is absent —
    the script warns). No letter-spacing tricks.
  * SRT cues must not overlap (overlapping cues cause vertical jitter in
    libass); overlapping cues are clipped, never silently kept.
  * Word-level karaoke: with --words words.json (from transcribe.py
    --format json) each word gets an ASS \\k duration tag.

Usage:
    python3 captions.py --input subs.srt --output subs.ass
    python3 captions.py --input subs.srt --output subs.ass --words words.json --karaoke
    python3 captions.py --input subs.srt --output subs.ass --font-size 48 --primary-color FFFFFF
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

RLI = "\u2067"
PDI = "\u2069"
RLM = "\u200f"

FA_RE = re.compile(r"[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]")


def has_persian(text: str) -> bool:
    return bool(FA_RE.search(text))


def rtl_wrap(text: str) -> str:
    """Wrap a Persian-containing line in RLI...PDI isolates.

    Latin runs inside a Persian line stay readable because the isolate
    scopes the direction; a trailing RLM keeps final punctuation on the
    correct side.
    """
    if not has_persian(text):
        return text
    return f"{RLI}{text}{PDI}{RLM}"


def parse_srt_time(t: str) -> float:
    m = re.match(r"(\d+):(\d+):(\d+)[,.](\d+)", t.strip())
    if not m:
        raise ValueError(f"bad SRT timestamp: {t!r}")
    h, mi, s, ms = (int(x) for x in m.groups())
    return h * 3600 + mi * 60 + s + ms / 1000.0


def ass_time(seconds: float) -> str:
    cs = max(0, int(round(seconds * 100)))
    h, rem = divmod(cs, 360_000)
    m, rem = divmod(rem, 6_000)
    s, cs = divmod(rem, 100)
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def parse_srt(path: str) -> list[dict]:
    with open(path, encoding="utf-8-sig") as fh:
        raw = fh.read()
    cues: list[dict] = []
    blocks = re.split(r"\n\s*\n", raw.strip())
    for block in blocks:
        lines = [ln for ln in block.splitlines() if ln.strip()]
        if len(lines) < 2:
            continue
        # First line may be an index number; find the timing line.
        timing_idx = next((i for i, ln in enumerate(lines)
                           if "-->" in ln), None)
        if timing_idx is None:
            raise ValueError(f"no timing line in SRT block: {block[:80]!r}")
        start_s, end_s = lines[timing_idx].split("-->")
        text = " ".join(lines[timing_idx + 1:])
        cues.append({"start": parse_srt_time(start_s),
                     "end": parse_srt_time(end_s), "text": text.strip()})
    if not cues:
        raise ValueError(f"no cues found in {path}")
    return cues


def ass_color(hex_rgb: str) -> str:
    """RRGGBB -> ASS &HBBGGRR (ASS stores BGR, alpha 00 = opaque)."""
    h = hex_rgb.lstrip("#")
    if len(h) != 6 or not re.fullmatch(r"[0-9A-Fa-f]{6}", h):
        raise ValueError(f"bad colour (expected RRGGBB): {hex_rgb!r}")
    r, g, b = h[0:2], h[2:4], h[4:6]
    return f"&H00{b}{g}{r}"


def build_ass(cues: list[dict], args: argparse.Namespace,
              karaoke_words: dict | None = None) -> str:
    # Clip overlaps: a cue must end before the next one starts.
    fixed = []
    for i, cue in enumerate(cues):
        start, end = cue["start"], cue["end"]
        if end <= start:
            print(f"WARNING: dropping cue with end<=start: {cue['text'][:40]!r}",
                  file=sys.stderr)
            continue
        if i + 1 < len(cues) and end > cues[i + 1]["start"]:
            end = cues[i + 1]["start"] - 0.01
            print(f"WARNING: clipped overlapping cue ending at {end:.2f}s "
                  f"(libass jitters on overlaps).", file=sys.stderr)
        fixed.append({**cue, "end": end})

    header = f"""[Script Info]
; RTL-safe ASS generated by motion-studio captions.py
; Render with: ffmpeg -i in.mp4 -vf "ass=subs.ass" out.mp4
; NEVER use ffmpeg drawtext for Persian — it breaks shaping/bidi.
ScriptType: v4.00+
PlayResX: {args.width}
PlayResY: {args.height}
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,{args.font},{args.font_size},{ass_color(args.primary_color)},{ass_color(args.secondary_color)},&H00000000,&H80000000,{args.bold},0,0,0,100,100,0,0,1,{args.outline},{args.shadow},2,{args.margin_x},{args.margin_x},{args.margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events = []
    for cue in fixed:
        text = cue["text"]
        if args.karaoke and karaoke_words is not None:
            key = round(cue["start"], 2)
            words = karaoke_words.get(key) or karaoke_words.get(str(key))
            if words:
                parts = []
                prev_end = cue["start"]
                for w in words:
                    dur_cs = max(1, int(round((w["end"] - w["start"]) * 100)))
                    gap = w["start"] - prev_end
                    if gap > 0.05:
                        parts.append(" ")
                    parts.append(f"{{\\k{dur_cs}}}{w['word'].strip()}")
                    prev_end = w["end"]
                text = "".join(parts)
                text = rtl_wrap(text) if has_persian(cue["text"]) else text
            else:
                text = rtl_wrap(text)
        else:
            text = rtl_wrap(text)
        # ASS escaping: literal backslash / braces are special.
        text = text.replace("\\", "\\\\") if "\\k" not in text else text
        events.append(
            f"Dialogue: 0,{ass_time(cue['start'])},{ass_time(cue['end'])},"
            f"Default,,0,0,0,,{text}")
    return header + "\n".join(events) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Convert SRT to RTL-safe ASS (libass) subtitles. "
                    "Never uses ffmpeg drawtext for Persian.")
    ap.add_argument("--input", required=True, help="Input .srt file.")
    ap.add_argument("--output", required=True, help="Output .ass file.")
    ap.add_argument("--words", default=None,
                    help="Word-timing JSON from transcribe.py --format json "
                         "(enables --karaoke).")
    ap.add_argument("--karaoke", action="store_true",
                    help="Emit word-level \\k karaoke tags (needs --words).")
    ap.add_argument("--font", default="Vazirmatn",
                    help="Font family (default Vazirmatn).")
    ap.add_argument("--font-size", type=int, default=48, help="Font size (default 48).")
    ap.add_argument("--primary-color", default="FFFFFF", help="Main text RRGGBB (default FFFFFF).")
    ap.add_argument("--secondary-color", default="FFD166",
                    help="Karaoke highlight RRGGBB (default FFD166).")
    ap.add_argument("--bold", type=int, default=-1, choices=[-1, 0],
                    help="Bold: -1 on, 0 off (default -1).")
    ap.add_argument("--outline", type=int, default=2, help="Outline width (default 2).")
    ap.add_argument("--shadow", type=int, default=1, help="Shadow depth (default 1).")
    ap.add_argument("--width", type=int, default=1080, help="PlayResX (default 1080).")
    ap.add_argument("--height", type=int, default=1920, help="PlayResY (default 1920).")
    ap.add_argument("--margin-x", type=int, default=60, help="Side margin px (default 60).")
    ap.add_argument("--margin-v", type=int, default=120, help="Bottom margin px (default 120).")
    args = ap.parse_args()

    if not os.path.isfile(args.input):
        print(f"ERROR: input file not found: {args.input}", file=sys.stderr)
        return 2
    if args.karaoke and not args.words:
        print("ERROR: --karaoke needs --words words.json (from transcribe.py "
              "--format json).", file=sys.stderr)
        return 2

    try:
        cues = parse_srt(args.input)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    karaoke_words = None
    if args.words:
        if not os.path.isfile(args.words):
            print(f"ERROR: words file not found: {args.words}", file=sys.stderr)
            return 2
        with open(args.words, encoding="utf-8") as fh:
            data = json.load(fh)
        karaoke_words = {round(seg["start"], 2): seg.get("words", [])
                         for seg in data}

    # Font availability warning (best effort via fc-list).
    import shutil, subprocess
    if shutil.which("fc-list"):
        out = subprocess.run(["fc-list", ":lang=fa", "family"],
                             capture_output=True, text=True)
        if args.font not in (out.stdout or ""):
            print(f"WARNING: font '{args.font}' not found by fc-list "
                  f"(check: fc-list :lang=fa). libass will fall back — "
                  f"install Vazirmatn for correct Persian rendering.",
                  file=sys.stderr)

    try:
        ass = build_ass(cues, args, karaoke_words)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(ass)
    n_fa = sum(1 for c in cues if has_persian(c["text"]))
    print(f"OK: {len(cues)} cues ({n_fa} Persian, RLI/PDI wrapped) -> {args.output}")
    print("Burn in with: "
          f"ffmpeg -i in.mp4 -vf \"ass={args.output}\" -c:a copy out.mp4")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
